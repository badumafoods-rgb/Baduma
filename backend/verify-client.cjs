const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const window={BadumaUI:{React:{createElement:()=>null},root:{render:()=>{}}},supabase:{createClient:()=>({})}};
vm.runInNewContext(fs.readFileSync(fs.existsSync('realtime.js')?'realtime.js':'dist/realtime.js','utf8'),{window});
const {normalizeCart,total}=window.BadumaLive;
const products=[{id:'egg-kottu',name:'Egg Kottu',product_variants:[{label:'Large',price_lkr:800}]}];
assert.deepEqual(JSON.parse(JSON.stringify(normalizeCart([{name:'Egg Kottu · Large + Extra cheese',quantity:2,price:1}],products))),[{product_id:'egg-kottu',variant:'Large',extras:['Extra cheese'],quantity:2}]);
assert.throws(()=>normalizeCart([{name:'Unknown · Large',quantity:1}],products));
assert.throws(()=>normalizeCart([{name:'Egg Kottu · Invalid',quantity:1}],products));
assert.equal(total({subtotal_lkr:1000,quoted_delivery_lkr:100,final_delivery_lkr:0,discount_lkr:50}),950);
assert.equal(total({subtotal_lkr:1000,quoted_delivery_lkr:100,final_delivery_lkr:null,discount_lkr:50}),1050);
const html=fs.readFileSync(fs.existsSync('index.html')?'index.html':'dist/index.html','utf8');
assert.ok(html.includes('await i({...b,'),'Checkout must await server acknowledgement before clearing cart');
assert.ok(html.includes('window.BadumaUI='),'Existing menu must be exposed to live application');
assert.ok(html.includes('/realtime.js'));
const sql=fs.readFileSync('backend/realtime.sql','utf8');
assert.ok(sql.includes('customer_id=auth.uid()'));
assert.ok(sql.includes('rider_id=auth.uid()'));
assert.ok(sql.includes("coalesce(public.baduma_staff_role(),'')<>'rider'"));
assert.ok(sql.includes("set search_path=''"));
console.log('Passed: cart mapping, invalid item/size rejection, total calculation, awaited checkout, and authorization assertions.');
